import 'dart:async';
import 'dart:convert';
import 'package:flutter_test/flutter_test.dart';
import 'package:herdr_flutter_probe/host_catalog.dart';
import 'package:herdr_flutter_probe/host_tabs.dart';
import 'package:herdr_flutter_probe/remote_adapter.dart' show RemoteFailure;
import 'host_catalog_test.dart' show catalogPairing,MemoryCatalogStorage;
import 'remote_test_data.dart';

void main() {
  HostProfile profile(String name,String provider) => HostProfile.create(name,fixtureConfig(),catalogPairing(authorized:true),1000,provider:provider);
  testWidgets('replacement revokes only the old profile, waits for its original close and rejects late callbacks', (tester) async {
    final tabs = HostTabs(), old = profile('Same label','unspecified'), peer = profile('Same label','unspecified');
    addTearDown(tabs.dispose);
    expect(old.id,isNot(peer.id));
    tabs.open(old); final a = tabs.active!;
    tabs.open(peer); final b = tabs.active!;
    tabs.splitWith(a.id);
    final close = Completer<void>();
    var aCloses = 0, bCloses = 0;
    a.registerTransport(() { aCloses++; return close.future; });
    b.registerTransport(() async { bCloses++; });
    final rejected = isA<RemoteFailure>().having((e) => e.code,'code','catalog_transfer_close_unconfirmed');
    final retirement = tabs.retireReplacedHosts({old.id},budget:const Duration(milliseconds:50));
    final expectation = expectLater(retirement,throwsA(rejected));
    expect(a.retired,isTrue);
    expect(a.view.value.state,'retiring');
    expect(a.binding,isNull);
    expect(a.authorization,isNull);
    expect(a.visible.value,isFalse);
    expect(a.inputEligible.value,isFalse);
    expect(tabs.active,same(b));
    expect(b.visible.value,isTrue);
    expect(b.inputEligible.value,isTrue);
    await tester.pump(const Duration(milliseconds:50)); await expectation;
    expect(a.view.value.state,'retired-unconfirmed');
    tabs.reconcile([old.change(enabled:false,retired:true,now:1000),peer]);
    a.report('live','late','late',DateTime.now());
    await tester.pump();
    expect(tabs.tabs,[a,b]);
    expect(a.view.value.state,'retired-unconfirmed');
    expect(a.view.value.frameAt,isNull);
    tabs.select(a.id);
    tabs.setSplitAvailable(false); tabs.setSplitAvailable(true);
    expect(a.visible.value,isFalse); expect(a.inputEligible.value,isFalse);
    final retry = tabs.retireReplacedHosts({old.id});
    close.complete(); await retry;
    expect(a.view.value.state,'retired');
    expect(aCloses,1); expect(bCloses,0);
    tabs.close(a.id);
    expect(tabs.tabs,[b]);
    expect(aCloses,1); expect(bCloses,0);
  });
  test('replacement failure stays unconfirmed after the historical label is manually closed', () async {
    final tabs = HostTabs(), old = profile('A','unspecified');
    addTearDown(tabs.dispose);
    tabs.open(old); final tab = tabs.active!;
    var closes = 0;
    tab.registerTransport(() async { closes++; throw StateError('fixture peer close unconfirmed'); });
    final rejected = isA<RemoteFailure>().having((e) => e.code,'code','catalog_transfer_close_unconfirmed');
    await expectLater(tabs.retireReplacedHosts({old.id}),throwsA(rejected));
    expect(tab.view.value.state,'retired-unconfirmed');
    tabs.close(tab.id);
    await expectLater(tabs.retireReplacedHosts({old.id}),throwsA(rejected));
    expect(tabs.tabs,isEmpty);
    expect(closes,1);
  });
  test('node stop joins a pending tab close without restarting either transport', () async {
    final tabs = HostTabs();
    addTearDown(tabs.dispose);
    tabs.open(profile('A', 'easytier'));
    final a = tabs.active!;
    tabs.open(profile('B', 'easytier'));
    final b = tabs.active!;
    final aClose = Completer<void>(), bClose = Completer<void>();
    final calls = <String>[];
    a.registerTransport(() { calls.add('A'); return aClose.future; });
    b.registerTransport(() { calls.add('B'); return bClose.future; });

    tabs.close(a.id);
    tabs.close(a.id);
    expect(calls, ['A']);
    expect(tabs.active, same(b));

    var settled = false;
    final stopping = tabs.closeHostsAndWait({a.hostId, b.hostId}).then((value) {
      settled = true;
      return value;
    });
    tabs.close(b.id);
    expect(calls, ['A', 'B']);
    expect(tabs.tabs, isEmpty);
    bClose.complete();
    await Future<void>.delayed(Duration.zero);
    expect(settled, isFalse);

    aClose.completeError(StateError('peer close was unconfirmed'));
    expect(await stopping, isFalse);
    expect(calls, ['A', 'B']);
  });
  test('select hides old lease first; tabs own navigators and never activate a sibling on close',() {
    final first = profile('A','tailscale'), second = profile('B','easytier'), tabs = HostTabs();
    tabs.open(first); final a = tabs.active!; final events = <String>[];
    a.visible.addListener(() => events.add('A:${a.visible.value}'));
    tabs.open(second); final b = tabs.active!; b.visible.addListener(() => events.add('B:${b.visible.value}'));
    expect(a.visible.value,isFalse); expect(b.visible.value,isTrue); expect(identical(a.navigator,b.navigator),isFalse);
    events.clear(); tabs.select(a.id); expect(events,['B:false','A:true']);
    expect(tabs.tabs.length,2); expect(tabs.active!.provider,'tailscale');
    tabs.close(a.id); expect(tabs.active,isNull); expect(b.visible.value,isFalse); tabs.dispose();
  });
  test('split keeps both observers visible and transfers the sole input lease before granting it',() {
    final tabs=HostTabs();
    tabs.open(profile('A','tailscale')); final a=tabs.active!;
    tabs.open(profile('B','easytier')); final b=tabs.active!;
    tabs.splitWith(a.id);
    expect(a.visible.value,isTrue); expect(b.visible.value,isTrue);
    expect(a.inputEligible.value,isFalse); expect(b.inputEligible.value,isTrue);
    final left=tabs.splitLeftId,events=<String>[];
    a.inputEligible.addListener(() => events.add('A:${a.inputEligible.value}'));
    b.inputEligible.addListener(() => events.add('B:${b.inputEligible.value}'));
    tabs.select(a.id);
    expect(events,['B:false','A:true']);
    expect(tabs.splitLeftId,left); expect(a.visible.value,isTrue); expect(b.visible.value,isTrue);
    tabs.closeSplit();
    expect(a.visible.value,isTrue); expect(a.inputEligible.value,isTrue);
    expect(b.visible.value,isFalse); expect(b.inputEligible.value,isFalse);
    tabs.dispose();
  });
  test('D2 stows only the secondary lease and can restore its original side', () {
    final tabs = HostTabs();
    addTearDown(tabs.dispose);
    tabs.open(profile('A', 'tailscale'));
    final a = tabs.active!;
    tabs.open(profile('B', 'easytier'));
    final b = tabs.active!;
    tabs.splitWith(a.id);
    tabs.select(a.id);
    final events = <String>[];
    a.inputEligible.addListener(() => events.add('A input: ${a.inputEligible.value}'));
    b.inputEligible.addListener(() => events.add('B input: ${b.inputEligible.value}'));
    b.visible.addListener(() => events.add('B visible: ${b.visible.value}'));

    tabs.setSplitAvailable(false);
    tabs.setSplitAvailable(false);
    expect(tabs.splitId, b.id);
    expect(tabs.splitLeftId, b.id);
    expect(tabs.active, same(a));
    expect(a.visible.value, isTrue);
    expect(a.inputEligible.value, isTrue);
    expect(b.visible.value, isFalse);
    expect(b.inputEligible.value, isFalse);
    tabs.setSplitAvailable(true);
    expect(events, ['B visible: false', 'B visible: true']);
    expect(tabs.active, same(a));
    expect(tabs.splitLeftId, b.id);
    expect(b.inputEligible.value, isFalse);
  });
  test('D2 does not revive a stowed split after selection, close or reconciliation', () {
    final tabs = HostTabs();
    addTearDown(tabs.dispose);
    final first = profile('A', 'tailscale');
    final second = profile('B', 'easytier');
    tabs.open(first);
    final a = tabs.active!;
    tabs.open(second);
    final b = tabs.active!;
    tabs.setSplitAvailable(false);
    tabs.splitWith(a.id);
    expect(tabs.splitId, isNull);
    tabs.setSplitAvailable(true);
    tabs.splitWith(a.id);
    tabs.setSplitAvailable(false);
    tabs.select(a.id);
    tabs.setSplitAvailable(true);
    expect(tabs.splitId, isNull);
    expect(tabs.active, same(a));
    expect(b.visible.value, isFalse);
    expect(b.inputEligible.value, isFalse);

    tabs.splitWith(b.id);
    tabs.setSplitAvailable(false);
    tabs.closeSplit();
    tabs.setSplitAvailable(true);
    expect(tabs.splitId, isNull);
    expect(b.visible.value, isFalse);

    tabs.splitWith(b.id);
    tabs.setSplitAvailable(false);
    tabs.reconcile([first, second.change(enabled: false, now: 1000)]);
    tabs.setSplitAvailable(true);
    expect(tabs.tabs, [a]);
    expect(tabs.active, same(a));
    expect(tabs.splitId, isNull);
    expect(tabs.splitLeftId, isNull);
  });
  test('MT01 MT06 same host has independent views; disabling it closes only its views',() {
    final p = profile('A','zerotier'), tabs = HostTabs(); tabs.open(p); final old = tabs.active;
    tabs.select(null); tabs.open(p); expect(identical(tabs.active,old),isFalse); expect(tabs.tabs.length,2);
    expect(tabs.active!.hostId,p.id); expect(tabs.active!.id,isNot(old!.id));
    final sibling = profile('B','easytier'); tabs.open(sibling); final siblingId = tabs.active!.id;
    tabs.reconcile([p.change(label:'Renamed',now:1000),sibling]); expect(tabs.forHost(p.id).every((t) => t.label == 'Renamed'),isTrue);
    tabs.reconcile([p.change(enabled:false,now:1000),sibling]); expect(tabs.tabs.length,1); expect(tabs.active!.id,siblingId); tabs.dispose();
  });
  test('MT06 view connection-status updates keep sibling tabs, but revoked authority closes them',() {
    final a = profile('A','tailscale'),b = profile('B','easytier'),tabs = HostTabs();
    tabs.open(a); tabs.open(a); tabs.open(b); final other = tabs.active!.id;
    final connected = a.restore(1000)..state = 'waiting-connectivity';
    final statusOnly = a.change(pairing:connected,now:1000);
    tabs.reconcile([statusOnly,b]); expect(tabs.forHost(a.id).length,2); expect(tabs.active!.id,other);
    final revoked = statusOnly.restore(1000)..authorization = 'revoked'..state = 'revoked'..consumed = true;
    tabs.reconcile([statusOnly.change(pairing:revoked,now:1000),b]);
    expect(tabs.forHost(a.id),isEmpty); expect(tabs.active!.id,other);
    tabs.dispose();
  });
  test('configured provider is an enum and old catalog v1 migrates to unknown network',() async {
    final p = profile('A','tailscale'); expect(p.toJson()['provider'],'tailscale');
    expect(() => p.change(provider:'connected',now:1000),throwsA(isA<Exception>()));
    final old = {...p.toJson()}..remove('provider');
    final storage = MemoryCatalogStorage()..contents = jsonEncode({'schemaVersion':1,'profiles':[old],'pendingCreation':null})..revision = List.filled(64,'a').join();
    final restored = HostCatalog(storage:storage,clock:() => 1000); await restored.load();
    expect(restored.ready,isTrue); expect(restored.profiles.single.provider,'unspecified'); expect(storage.writes,0); restored.dispose();
  });
  test('eight view limit and host-scoped close preserve other hosts',() {
    final a = profile('A','tailscale'),b = profile('B','easytier'),tabs = HostTabs();
    for (var i = 0; i < 7; i++) { expect(tabs.open(a),isTrue); }
    expect(tabs.open(b),isTrue); final bId = tabs.active!.id;
    expect(tabs.open(a),isFalse); expect(tabs.tabs.length,8);
    final ids = tabs.forHost(a.id).map((t) => t.id).toSet(); expect(ids.length,7);
    tabs.closeHost(a.id); expect(tabs.tabs.single.id,bId); expect(tabs.active!.id,bId);
    expect(tabs.open(a),isTrue); expect(ids.contains(tabs.active!.id),isFalse);
    tabs.dispose();
  });
}
