#!/usr/bin/env python3
"""Fail-closed OCR of pixels in a measured terminal rectangle.

The caller must capture the real application after input was received by its
owned SSH peer. The marker and per-peer token must both occur inside the
terminal crop. No application buffer, DOM text, or OCR transcript is evidence.
Tesseract CLI: https://tesseract-ocr.github.io/tessdoc/Command-Line-Usage.html
"""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
from screen_proof_token import token_lines


ECHO_MARKER = 'POCKET-ANDROID-SSH-OK'


class ScreenshotGateError(RuntimeError):
    """A public failure code with bounded, transcript-free diagnostics."""

    def __init__(self, code, evidence=None):
        super().__init__(code)
        self.evidence = evidence or {}


def _normalized_line(line):
    # OCR can separate a monospace word or use a Unicode dash. Do not accept
    # fuzzy characters, prefixes/suffixes, or concatenate separate lines.
    return re.sub(r'[\s\-\u2010-\u2015\u2212]', '', line.upper()).strip('$> ')


def _contains_line(text, expected):
    return any(_normalized_line(line) == _normalized_line(expected) for line in text.splitlines())


def _contains_adjacent_lines(text, expected):
    # Empty OCR spacing is harmless; a visible prompt or other content still
    # occupies a row and cannot be skipped to manufacture adjacency.
    rows = [_normalized_line(line) for line in text.splitlines() if line.strip()]
    wanted = [_normalized_line(line) for line in expected]
    return any(rows[index:index + len(wanted)] == wanted for index in range(len(rows) - len(wanted) + 1))


def verify_terminal_screenshot(png, *, expected_token, bounds):
    """Verify a PNG's terminal pixels; bounds is (x, y, width, height).

    Returns only public pixel predicates, hashes, geometry, and engine version.
    A fresh token generated by the SSH fixture prevents reuse of old captures.
    The crop must be measured from the displayed terminal, excluding app chrome
    and input fields. Cropping never changes the retained original screenshot.
    """
    try:
        proof_lines = token_lines(expected_token)
    except ValueError:
        raise ScreenshotGateError('terminal_screenshot_token_invalid')
    if (not isinstance(bounds, (tuple, list)) or len(bounds) != 4 or
            any(type(value) is not int for value in bounds)):
        raise ScreenshotGateError('terminal_screenshot_bounds_invalid')
    try:
        from PIL import Image, ImageChops, ImageOps, ImageStat
    except ImportError:
        raise ScreenshotGateError('terminal_screenshot_pillow_missing') from None
    try:
        data = png if isinstance(png, bytes) else Path(png).read_bytes()
        if not data.startswith(b'\x89PNG\r\n\x1a\n') or len(data) > 8_000_000:
            raise ValueError()
        with Image.open(io.BytesIO(data)) as source:
            if source.format != 'PNG' or source.width * source.height > 16_000_000:
                raise ValueError()
            source.load()
            image = source.convert('RGB')
    except (OSError, ValueError, Image.DecompressionBombError):
        raise ScreenshotGateError('terminal_screenshot_png_invalid') from None
    x, y, width, height = bounds
    if x < 0 or y < 0 or width < 1 or height < 1 or x + width > image.width or y + height > image.height:
        raise ScreenshotGateError('terminal_screenshot_bounds_invalid')
    evidence = {'schemaVersion': 1, 'imageSha256': hashlib.sha256(data).hexdigest(),
                'imageSize': [image.width, image.height], 'terminalBounds': list(bounds),
                'expectedMarker': ECHO_MARKER, 'expectedToken': expected_token,
                'markerVisible': False, 'tokenVisible': False}
    executable = shutil.which('tesseract')
    if executable is None:
        raise ScreenshotGateError('terminal_screenshot_ocr_missing', evidence)
    crop = image.crop((x, y, x + width, y + height))
    # Brightness preserves colored ANSI glyphs. A white border and 2x sampling
    # help small terminal fonts without reference glyphs or layout templates.
    red, green, blue = crop.split()
    gray = ImageOps.autocontrast(ImageChops.lighter(ImageChops.lighter(red, green), blue))
    if ImageStat.Stat(gray).mean[0] < 127:
        gray = ImageOps.invert(gray)
    gray = ImageOps.expand(gray.resize((width * 2, height * 2)), border=20, fill=255)
    encoded = io.BytesIO()
    gray.save(encoded, format='PNG')
    ocr_env = dict(os.environ, OMP_THREAD_LIMIT='1')
    try:
        version = subprocess.run([executable, '--version'], capture_output=True, timeout=10, check=True, env=ocr_env)
        match = re.match(rb'tesseract ([0-9.]+)', version.stdout)
        if match is None:
            raise ValueError()
        evidence['ocrEngine'] = 'tesseract ' + match[1].decode('ascii')
        # Sparse terminal lines can be segmented incorrectly as one text block
        # even with the real bundled font. Retry segmentation, never characters.
        # Both exact lines must occur in the SAME recognition result.
        for attempt, psm in enumerate((6, 11), start=1):
            evidence['ocrAttempts'] = attempt
            result = subprocess.run([executable, 'stdin', 'stdout', '-l', 'eng', '--psm', str(psm),
                                     '-c', 'load_system_dawg=0', '-c', 'load_freq_dawg=0'],
                                    input=encoded.getvalue(), capture_output=True, timeout=30, check=True, env=ocr_env)
            text = result.stdout.decode('utf-8', errors='strict')
            marker_visible = _contains_line(text, ECHO_MARKER)
            token_visible = _contains_adjacent_lines(text, proof_lines)
            sequence_visible = _contains_adjacent_lines(text, (ECHO_MARKER, *proof_lines))
            if int(marker_visible) + int(token_visible) >= int(evidence['markerVisible']) + int(evidence['tokenVisible']):
                evidence.update(markerVisible=marker_visible, tokenVisible=token_visible,
                                ocrPageSegmentationMode=psm, proofSequenceVisible=sequence_visible)
            if marker_visible and token_visible and sequence_visible:
                return evidence
    except (OSError, subprocess.SubprocessError, UnicodeError, ValueError):
        raise ScreenshotGateError('terminal_screenshot_ocr_failed', evidence) from None
    if not evidence['markerVisible']:
        raise ScreenshotGateError('terminal_screenshot_echo_not_visible', evidence)
    if not evidence['tokenVisible']:
        raise ScreenshotGateError('terminal_screenshot_token_not_visible', evidence)
    if not evidence.get('proofSequenceVisible'):
        raise ScreenshotGateError('terminal_screenshot_proof_not_adjacent', evidence)
    return evidence


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image', required=True, type=Path)
    parser.add_argument('--token', required=True)
    parser.add_argument('--bounds', required=True, help='x,y,width,height in original screenshot pixels')
    args = parser.parse_args()
    try:
        bounds = tuple(int(value) for value in args.bounds.split(','))
    except ValueError:
        parser.error('--bounds must contain four comma-separated integers')
    try:
        evidence = verify_terminal_screenshot(args.image, expected_token=args.token, bounds=bounds)
    except ScreenshotGateError as error:
        print(json.dumps({'status': 'failed', 'error': str(error), **error.evidence}, sort_keys=True))
        return 1
    print(json.dumps({'status': 'passed', **evidence}, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
