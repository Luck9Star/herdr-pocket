"""Real, newly created local PTYs only; no shell, credentials or GUI.

The controlled subprocess owns its session/PTY. No terminal output/history is
read except for the synthetic output generated by these owned fixtures; tests
inspect only numeric JSON, owned termios attributes and synthetic bytes.
"""
from contextlib import contextmanager
